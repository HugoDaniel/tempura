#!/bin/sh
# Render docs/timeline-language.md from schema/tempura.sjon.
#
# The manifest already carries a `:description` on every form, key and
# value kind — that prose IS the timeline language's documentation, and
# this makes it a page instead of leaving it readable only by a validator.
# One source, so the reference cannot drift from the rules.
#
#   tools/timeline_docs.sh <path-to-sjon-cli> [--update]
#
# Default mode CHECKS: it re-renders to a temp file and diffs against the
# committed page, failing if they differ (this is the leg `zig build
# verify` depends on). `--update` writes the page instead. Both go through
# the same render, so the gate compares exactly what the verb produces.
#
# Why the render feeds the exporter TWO manifests and then throws one
# away. `(keyframe :ease …)` is typed `pacer/ease-spec`, a cross-plugin
# kind reference into the verbatim pacer copy (LANGUAGE.md §6.7), and
# `export-schema` resolves a manifest's type references against that
# manifest alone. It does NOT compose `sjon-project.sjon`'s plugins, even
# though `sjon project info` finds the project from this same directory —
# measured on SJON 1.4.2, where
#
#   sjon export-schema schema/tempura.sjon --target=markdown
#   sjon export-schema schema/tempura.sjon --target=markdown --no-project
#
# produce BYTE-IDENTICAL pages and both exit 1 with
# `[err aggregate_phase_error] value-type reference pacer/ease-spec does
# not resolve to any value-kind`. So the direct render is not an option
# here, and it would not be the one to want anyway: it prints the `:ease`
# slot as an opaque `pacer/ease-spec?` with no constraints column, while
# the concatenated render resolves the kind and prints pacer's eighteen
# easing names in full — which is the answer an author reading the page
# is after.
#
# Concatenating the pacer copy AHEAD of the manifest is the whole fix: the
# exporter emits one page with a `# <plugin>` section per manifest in
# source order, and this script keeps the second. pacer's own reference is
# `docs/score-language.md` in pacer's repo and is not restated here.
set -eu

SJON="${1:?usage: timeline_docs.sh <sjon-cli> [--update]}"
MODE="${2:-check}"
MANIFEST="schema/tempura.sjon"
PACER="schema/pacer.sjon"
PAGE="docs/timeline-language.md"

tmp_out=$(mktemp)
tmp_err=$(mktemp)
tmp_src=$(mktemp)
tmp_dir=$(mktemp -d)
trap 'rm -rf "$tmp_out" "$tmp_err" "$tmp_src" "$tmp_dir"' EXIT

cat "$PACER" "$MANIFEST" >"$tmp_src"

# Render into a directory of its own rather than through `--output=-`: the
# CLI's stdout writer is positional, so anything already written to a
# redirected stdout (the header line, say) is overwritten from offset 0.
# The exporter also narrates its lossy JSON-Schema mappings on stderr
# (`[info …]` and a `[warn …]` per cross-ref) — kept for a failure,
# swallowed otherwise so a clean `verify` stays quiet.
if ! "$SJON" export-schema "$tmp_src" --target=markdown --output="$tmp_dir" 2>"$tmp_err"; then
    echo "timeline-docs: export-schema failed:" >&2
    cat "$tmp_err" >&2
    exit 1
fi

set -- "$tmp_dir"/*.md
if [ "$#" -ne 1 ] || [ ! -f "$1" ]; then
    echo "timeline-docs: expected exactly one rendered page, got $#" >&2
    exit 1
fi
rendered="$1"

# The exporter writes a `# <plugin>` section per manifest in source order.
# Keep the second one's body — everything from the `# tempura` heading to
# the end of the file, minus that heading, which the preamble replaces.
if ! grep -q '^# tempura$' "$rendered"; then
    echo "timeline-docs: the rendered page has no '# tempura' section" >&2
    exit 1
fi

{
    cat <<'HEADER'
<!-- GENERATED by `zig build docs` from schema/tempura.sjon — do not hand-edit. -->

# The tempura timeline language

Every form, key and value kind of the `(timeline …)` vocabulary, rendered from
`schema/tempura.sjon`'s own `:description`s. The manifest is the single source:
edit it, run `zig build docs`, and review the diff — `zig build verify` fails
when the page and the manifest disagree.

What is here is what one form can say about itself. The rules that are relations
BETWEEN forms — document order, an anchor's digest, a bound lane's address, two
notes overlapping on one key — are tempura's own diagnostics, and
[`docs/plans/02-timeline-schema.md`](plans/02-timeline-schema.md) is where they
are written down.

The hosted `midi/` and `it/` tiers (`schema/midi.sjon`, `schema/it.sjon`) and
the verbatim pacer copy (`schema/pacer.sjon`) are separate vocabularies with
their own references; only the timeline tier is rendered here.
HEADER
    sed -n '/^# tempura$/,$p' "$rendered" | tail -n +2
} >"$tmp_out"

if [ "$MODE" = "--update" ]; then
    cp "$tmp_out" "$PAGE"
    # `mktemp` makes the temp file 0600 and `cp` carries that mode onto a
    # page that does not exist yet, so a freshly generated page would be
    # committed unreadable. Pin it to the repo's own mode instead.
    chmod 644 "$PAGE"
    echo "timeline-docs: wrote $PAGE"
    exit 0
fi

if ! diff -u "$PAGE" "$tmp_out"; then
    echo "timeline-docs: $PAGE is stale — \`zig build docs\` regenerates it" >&2
    exit 1
fi
echo "timeline-docs: $PAGE is current"
