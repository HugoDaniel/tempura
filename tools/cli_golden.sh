#!/bin/sh
# Pin the `tempura` CLI's output, channel by channel.
#
#   tools/cli_golden.sh <path-to-tempura-cli> [--update]
#
# It takes an ALREADY BUILT binary and never compiles anything itself, so
# it is safe to run at any time: `build.zig` hands it `cli_exe` through
# `addArtifactArg`, and every compile on this machine goes through
# `tools/zt` (the serialised `zig build` wrapper).
#
# Default mode CHECKS: it re-runs each case into a temp file and diffs
# against the committed golden, failing if they differ (this is the leg
# `zig build verify` depends on). `--update` writes the goldens instead.
# Both go through the same run, so the gate compares what the verb would
# actually produce.
#
# WHY a golden on top of the in-process tests: those check shape and rules
# one assertion at a time. A golden checks the WHOLE output in one
# reviewable diff, and catches a reshuffle nothing happened to assert.
#
# WHY all three channels in one file: plan 10's contract is not only what
# the CLI says but WHERE — "diagnostics to stderr, artifacts to stdout or
# `-o`" — and an exit code nobody can pipe. A golden that recorded stdout
# alone would pass a version of `dump` that wrote its document to stderr.
#
# These live in `src/cli/testdata/`, deliberately NOT in `corpus/`. That
# directory's contract is native == wasm byte for byte; the CLI is
# native-only and makes no parity claim, so mixing them would dilute a
# gate whose sharpness is the whole point. The FIXTURES the cases run over
# are the corpus's, because those are already hash-pinned by
# `corpus/*/expected.sjon` — so a regenerated fixture fails there as well
# as here, and both diffs get reviewed together.
set -eu

CLI="${1:?usage: cli_golden.sh <tempura-cli> [--update]}"
MODE="${2:-check}"
DIR="src/cli/testdata"

status=0
out=$(mktemp)
err=$(mktemp)
got=$(mktemp)
trap 'rm -f "$out" "$err" "$got"' EXIT

# sha256 of stdin, whichever of the two usual tools this host has. Used
# for the one case whose artifact is BYTES: a `.mid` in a golden would be
# unreviewable, and its digest is exactly as sharp.
digest() {
    if command -v sha256sum >/dev/null 2>&1; then
        sha256sum | cut -d' ' -f1
    else
        shasum -a 256 | cut -d' ' -f1
    fi
}

# run_case <golden-name> <expected-exit> <newline-separated argv> [hash]
run_case() {
    name=$1
    want_exit=$2
    argv=$3
    how=${4:-text}
    golden="$DIR/$name.txt"

    # Split argv on newlines so a case can carry many flags readably.
    # Everything this function needs from its OWN parameters is read
    # first: `set --` below replaces them with the split argv.
    old_ifs=$IFS
    IFS='
'
    # shellcheck disable=SC2086
    set -- $argv
    IFS=$old_ifs

    got_exit=0
    "$CLI" "$@" >"$out" 2>"$err" || got_exit=$?

    {
        echo "# tempura CLI golden — GENERATED by \`zig build cli-golden\`; do not hand-edit."
        echo "# argv: $(echo "$argv" | tr '\n' ' ')"
        echo "exit: $got_exit"
        if [ "$how" = "hash" ]; then
            echo "--- stdout ($(wc -c <"$out" | tr -d ' ') bytes, sha256 $(digest <"$out"))"
        else
            echo "--- stdout ($(wc -c <"$out" | tr -d ' ') bytes)"
            cat "$out"
            echo ""
        fi
        echo "--- stderr ($(wc -c <"$err" | tr -d ' ') bytes)"
        cat "$err"
        echo ""
    } >"$got"

    if [ "$got_exit" -ne "$want_exit" ] && [ "$MODE" != "--update" ]; then
        echo "cli-golden: $name: exit $got_exit, expected $want_exit" >&2
        status=1
        return
    fi

    if [ "$MODE" = "--update" ]; then
        cp "$got" "$golden"
        echo "cli-golden: wrote $golden"
        return
    fi
    if [ ! -f "$golden" ]; then
        echo "cli-golden: $golden is missing — \`zig build cli-golden\` writes it" >&2
        status=1
        return
    fi
    if ! diff -u "$golden" "$got"; then
        echo "cli-golden: $golden is stale — \`zig build cli-golden\` regenerates it (review the diff)" >&2
        status=1
    fi
}

