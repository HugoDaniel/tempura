/** Uppercase fixed-width hex — Zig's `{X:0>w}`. */
const hex = (value, width) => value.toString(16).toUpperCase().padStart(width, '0');

const f64Bits = (x) => {
  const dv = new DataView(new ArrayBuffer(8));
  dv.setFloat64(0, x);
  return dv.getBigUint64(0);
};
const f64FromBits = (bits) => {
  const dv = new DataView(new ArrayBuffer(8));
  dv.setBigUint64(0, bits);
  return dv.getFloat64(0);
};

/**
 * An f64 as Zig's `{d}` prints it: the shortest decimal that round-trips,
 * never an exponent. JS's own `toString` is the same shortest form, and
 * the guard is what keeps a silent divergence from passing as a match.
 * @param {number} x
 * @returns {string}
 */
function zigDecimal(x) {
  const text = String(x);
  if (text.includes('e') || text.includes('E')) {
    throw new Error(`tempura: ${text} needs an exponent, which Zig's {d} does not print`);
  }
  return text;
}

/** A golden's string escaping: a `"` or a `\` inside one is escaped. */
function escapeText(text) {
  let out = '';
  for (const ch of text) {
    if (ch.codePointAt(0) < 0x20) throw new Error('control byte in a golden string');
    if (ch === '"' || ch === '\\') out += '\\';
    out += ch;
  }
  return out;
}

const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex');

/**
 * `(diag …)` children at `indent`, the runner's `renderDiags`.
 * @param {ReadonlyArray<import('../src/types.js').Diagnostic>} diags
 * @param {string} indent
 */
function renderDiags(diags, indent) {
  let out = '';
  for (const d of diags) {
    out += `\n${indent}(diag :code ${d.code} :severity ${d.severity}`;
    out += ` :start ${d.start} :end ${d.end} :message "${escapeText(d.message)}")`;
  }
  return out;
}

/**
 * The `(echo …)` block: the map's echo, the sections, the cues, the
 * lanes, then the document's report and the derivation's, in that order.
 *
 * @param {import('../src/types.js').Timeline} tl
 * @param {ReadonlyArray<import('../src/types.js').Diagnostic>} diags
 */
function renderEcho(tl, diags) {
  let out = '(echo';
  for (const s of tl.segments) {
    out += `\n  (segment :tick ${s.tick} :us ${zigDecimal(s.us)}`;
    out += ` :tps "${hex(f64Bits(s.ticksPerSecond), 16)}"`;
    out += ` :start-sec "${hex(f64Bits(s.startSeconds), 16)}")`;
  }
  for (const m of tl.meters) {
    out += `\n  (meter :tick ${m.tick} :sig [${m.n} ${m.d}] :first-bar ${m.firstBar})`;
  }
  out += `\n  (bars :count ${tl.bars.count} :last-start ${tl.bars.lastStart})`;
  out += `\n  (length :tick ${tl.length} :end ${tl.end}`;
  out += ` :loop-secs "${hex(f64Bits(tl.loopSeconds), 16)}")`;
  for (const s of tl.sections) {
    out += `\n  (section :name ${s.name} :at ${s.at} :dur ${s.dur})`;
  }
  for (const c of tl.cues) {
    out += `\n  (cue :name "${escapeText(c.name)}" :at ${c.at})`;
  }
  for (const l of tl.lanes) {
    out += `\n  (lane :name ${l.name} :kind ${l.kind} :onsets ${l.onsets}`;
    out += ` :first ${l.firstTick} :last ${l.lastTick})`;
  }
  // The runner renders the DOCUMENT's list then the DERIVATION's; the
  // blob carries both in that order with a `stage` byte, so the split is
  // the wire's and not a guess.
  out += renderDiags(
    diags.filter((d) => d.stage !== 'derivation'),
    '  ',
  );
  out += renderDiags(
    diags.filter((d) => d.stage === 'derivation'),
    '  ',
  );
  return `${out})\n`;
}

/**
 * One `(at …)` line. `:seconds` is present exactly when the question was
 * asked in seconds, which is what tells the two queries apart in a
 * golden read on its own.
 *
 * @param {import('../src/types.js').Playhead} pos
 * @param {bigint | null} secondsBits
 */
function renderPosition(pos, secondsBits) {
  let out = '(at';
  if (secondsBits !== null) out += ` :seconds "${hex(secondsBits, 16)}"`;
  if (pos.refused) return `${out} :refused ${REFUSALS[pos.refused]})\n`;
  out += ` :tick ${pos.tick} :bar ${pos.bar} :beat ${pos.beat} :sub ${pos.subTicks}`;
  out += ` :into-bar "${hex(f64Bits(pos.secondsIntoBar), 16)}"`;
  out += ` :sections [${pos.sectionIds.join(' ')}]`;
  out += ` :prev-cue ${pos.prevCue === null ? 'none' : pos.prevCue}`;
  out += ` :next-cue ${pos.nextCue === null ? 'none' : pos.nextCue}`;
  if (pos.orderRow) {
    out += ` :order ${pos.orderRow.order} :row ${pos.orderRow.row}`;
    out += ` :tick-in-row ${pos.orderRow.tickInRow}`;
  }
  return `${out})\n`;
}

