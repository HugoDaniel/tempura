// The wasm half of the determinism gate: walk `corpus/<case>/`, drive the
// SAME directives its `times.sjon` spells through `tempura.wasm`, render
// the canonical golden text from the raw blobs, and compare byte-equal
// against the `expected.sjon` the native runner (`src/corpus_runner.zig`)
// wrote. Native green + this green ⇒ native and wasm32 give identical
// answers for every pinned (document, query, directive) — pacer's rule.
//
// The canonical format is defined in `src/corpus_runner.zig`'s header;
// regenerate goldens with `zig build corpus -- --update` (never here —
// the native rendering is the AUTHORITY and this file only re-derives it).
//
// ## What the wasm can re-derive, and what it cannot
//
// The `tpr_*` surface is frozen (plan 10) and is deliberately a HOST's
// surface, not the corpus runner's: it has no export that reads a file
// into its core's own value, no canonical re-print, and no round-trip
// ladder. So five of the runner's nine directives have no wasm spelling,
// and this walk states which rather than quietly rendering less:
//
//   (read) (roundtrip) (walk) (write)  — they ask about BYTES through
//       `smf.read` / `itf.read` / the writers, and no export hands those
//       values out. The wasm's `tpr_loadFile` runs the readers, but what
//       comes back is a DOCUMENT, not a `Sequence` or a `RowMap`.
//   (dump) — the golden hashes a CANONICAL RE-PRINT of the timeline tier
//       with the file tiers lifted off. `tpr_text()` is the document's own
//       source (that is plan 04's essence and plan 07's layout rule: what
//       comes back is what a human wrote), so it is a different text on
//       purpose, and no export prints the other one.
//
// …and two the wasm serves only in part:
//
//   (build :cc N) — `tpr_build(kind)` carries no `--cc`, so a case that
//       renders a curve onto a controller is native-only.
//   (built …)'s children — `(rung1 …)` needs the reader, `(residue …)`
//       the record counts, `(rung3 …)` the dump. The HEAD of the form —
//       `:kind`, `:len`, `:sha256` — is the determinism claim itself
//       ("same document ⇒ same bytes on x86_64, aarch64 and wasm32"), and
//       that is compared. An ANCHORED document's `(built …)` comes out of
//       the runner's own inline-tier writer rather than out of
//       `pipeline.build`, and the golden says so by carrying no
//       `(residue …)` child — those are native-only too.
//
// Everything else IS compared, byte for byte: the `(fixture …)` line, the
// whole `(echo …)` block (from 'TPTL' + 'TPDG'), every `(at …)` from
// `(times …)` and `(at …)`, and every `(snapped …)`.
//
// The last test pins the native-only set, so a directive that stops being
// comparable — or one that starts being — fails loudly instead of
// shrinking the gate in silence.

import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { test } from 'node:test';
import { fileURLToPath } from 'node:url';

import { Tempura } from '../src/index.js';

const corpusDir = fileURLToPath(new URL('../../../corpus/', import.meta.url));
const wasmPath = fileURLToPath(new URL('../tempura.wasm', import.meta.url));
const wasmModule = new WebAssembly.Module(readFileSync(wasmPath));

const GENERATED_HEADER =
  '; tempura corpus golden — GENERATED by `zig build corpus -- --update`; do not hand-edit.';

/** Mirror of `TprAbi.Refusal`, kebab-case as the golden spells a guard. */
const REFUSALS = { 'tick-overflow': 'tick-overflow', 'non-finite-time': 'non-finite-time' };

/**
 * What the walk could not serve, and why — the reasons alone, not the
 * cases. Pinning the REASONS rather than a case list is deliberate: the
 * corpus grows with every feature, and a gate that had to be re-listed
 * for each new case would be edited by whoever is least interested in
 * it. A new reason, on the other hand, is a new hole in the surface and
 * has to be argued for.
 * @type {Set<string>}
 */
const nativeOnly = new Set();

/** How many of each form this walk actually compared, byte for byte. */
const compared = { fixture: 0, echo: 0, at: 0, snapped: 0, built: 0 };

/**
 * Record that a form went uncompared, and why. The case's own name is
 * not kept: see `nativeOnly`.
 * @param {string} reason
 */
function skipped(reason) {
  nativeOnly.add(reason);
}

// ---------------------------------------------------------------------------
// The harness
// ---------------------------------------------------------------------------

/**
 * Parse `times.sjon` — the constrained read pacer's corpus test uses:
 * flat forms, no nesting, `;` comments to end of line (stripped outside
 * strings). The native runner parses the same file with real SJON
 * against `schema/tempura-corpus.sjon` and is the stricter check; this
 * only has to agree with it on what was asked and in what order.
 *
 * @param {string} src
 * @returns {Array<Record<string, unknown> & { head: string }>}
 */
function parseHarness(src) {
  const stripped = src.replace(/"(?:[^"\\]|\\.)*"|;[^\n]*/g, (m) => (m.startsWith('"') ? m : ''));
  /** @type {Array<Record<string, unknown> & { head: string }>} */
  const out = [];
  for (const m of stripped.matchAll(/\(([a-z][a-z0-9-]*)([^)]*)\)/g)) {
    const head = m[1] ?? '';
    const body = m[2] ?? '';
    /** @type {Record<string, unknown> & { head: string }} */
    const form = { head };
    for (const kv of body.matchAll(/:([a-z0-9-]+)\s+("[^"]*"|[^\s):]+)/g)) {
      const key = kv[1] ?? '';
      const raw = kv[2] ?? '';
      form[key] = raw.startsWith('"') ? raw.slice(1, -1) : raw;
    }
    // `(times …)` carries its seconds positionally, as bit patterns;
    // every other form's strings are keyed and were read above.
    form.positional =
      head === 'times' ? [...body.matchAll(/"([0-9A-Fa-f]{16})"/g)].map((x) => x[1] ?? '') : [];
    out.push(form);
  }
  return out;
}

// ---------------------------------------------------------------------------
// The golden, as chunks
// ---------------------------------------------------------------------------

/**
 * Split a golden into its top-level forms. A chunk starts at a line
 * beginning with `(` in column 0 and takes every line after it that is a
 * continuation (indented) or a dumped tier line (`;| `).
 *
 * @param {string} text
 * @returns {string[]} each chunk with its trailing newline
 */
function chunksOf(text) {
  const lines = text.split('\n');
  /** @type {string[]} */
  const out = [];
  /** @type {string[]} */
  let current = [];
  for (const line of lines) {
    if (line.startsWith('(')) {
      if (current.length) out.push(`${current.join('\n')}\n`);
      current = [line];
    } else if (current.length && (line.startsWith(' ') || line.startsWith(';|'))) {
      current.push(line);
    } else if (current.length && line === '') {
      // The trailing newline of the file; the split already gave it.
    }
  }
  if (current.length) out.push(`${current.join('\n')}\n`);
  return out;
}

// ---------------------------------------------------------------------------
// Canonical rendering — the runner's format, in JS
// ---------------------------------------------------------------------------

/** Uppercase fixed-width hex — Zig's `{X:0>w}`. */
const hex = (value, width) => value.toString(16).toUpperCase().padStart(width, '0');

const f64Bits = (x) => {
  const dv = new DataView(new ArrayBuffer(8));
  dv.setFloat64(0, x);
  return dv.getBigUint64(0);
};
const f64FromBits = (bits) => {
  const dv = new DataView(new ArrayBuffer(8));
  dv.setBigUint64(0, bits);
  return dv.getFloat64(0);
};

/**
 * An f64 as Zig's `{d}` prints it: the shortest decimal that round-trips,
 * never an exponent. JS's own `toString` is the same shortest form, and
 * the guard is what keeps a silent divergence from passing as a match.
 * @param {number} x
 * @returns {string}
 */
function zigDecimal(x) {
  const text = String(x);
  if (text.includes('e') || text.includes('E')) {
    throw new Error(`tempura: ${text} needs an exponent, which Zig's {d} does not print`);
  }
  return text;
}

/** A golden's string escaping: a `"` or a `\` inside one is escaped. */
function escapeText(text) {
  let out = '';
  for (const ch of text) {
    if (ch.codePointAt(0) < 0x20) throw new Error('control byte in a golden string');
    if (ch === '"' || ch === '\\') out += '\\';
    out += ch;
  }
  return out;
}

const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex');

/**
 * `(diag …)` children at `indent`, the runner's `renderDiags`.
 * @param {ReadonlyArray<import('../src/types.js').Diagnostic>} diags
 * @param {string} indent
 */
function renderDiags(diags, indent) {
  let out = '';
  for (const d of diags) {
    out += `\n${indent}(diag :code ${d.code} :severity ${d.severity}`;
    out += ` :start ${d.start} :end ${d.end} :message "${escapeText(d.message)}")`;
  }
  return out;
}

/**
 * The `(echo …)` block: the map's echo, the sections, the cues, the
 * lanes, then the document's report and the derivation's, in that order.
 *
 * @param {import('../src/types.js').Timeline} tl
 * @param {ReadonlyArray<import('../src/types.js').Diagnostic>} diags
 */
function renderEcho(tl, diags) {
  let out = '(echo';
  for (const s of tl.segments) {
    out += `\n  (segment :tick ${s.tick} :us ${zigDecimal(s.us)}`;
    out += ` :tps "${hex(f64Bits(s.ticksPerSecond), 16)}"`;
    out += ` :start-sec "${hex(f64Bits(s.startSeconds), 16)}")`;
  }
  for (const m of tl.meters) {
    out += `\n  (meter :tick ${m.tick} :sig [${m.n} ${m.d}] :first-bar ${m.firstBar})`;
  }
  out += `\n  (bars :count ${tl.bars.count} :last-start ${tl.bars.lastStart})`;
  out += `\n  (length :tick ${tl.length} :end ${tl.end}`;
  out += ` :loop-secs "${hex(f64Bits(tl.loopSeconds), 16)}")`;
  for (const s of tl.sections) {
    out += `\n  (section :name ${s.name} :at ${s.at} :dur ${s.dur})`;
  }
  for (const c of tl.cues) {
    out += `\n  (cue :name "${escapeText(c.name)}" :at ${c.at})`;
  }
  for (const l of tl.lanes) {
    out += `\n  (lane :name ${l.name} :kind ${l.kind} :onsets ${l.onsets}`;
    out += ` :first ${l.firstTick} :last ${l.lastTick})`;
  }
  // The runner renders the DOCUMENT's list then the DERIVATION's; the
  // blob carries both in that order with a `stage` byte, so the split is
  // the wire's and not a guess.
  out += renderDiags(
    diags.filter((d) => d.stage !== 'derivation'),
    '  ',
  );
  out += renderDiags(
    diags.filter((d) => d.stage === 'derivation'),
    '  ',
  );
  return `${out})\n`;
}

/**
 * One `(at …)` line. `:seconds` is present exactly when the question was
 * asked in seconds, which is what tells the two queries apart in a
 * golden read on its own.
 *
 * @param {import('../src/types.js').Playhead} pos
 * @param {bigint | null} secondsBits
 */
function renderPosition(pos, secondsBits) {
  let out = '(at';
  if (secondsBits !== null) out += ` :seconds "${hex(secondsBits, 16)}"`;
  if (pos.refused) return `${out} :refused ${REFUSALS[pos.refused]})\n`;
  out += ` :tick ${pos.tick} :bar ${pos.bar} :beat ${pos.beat} :sub ${pos.subTicks}`;
  out += ` :into-bar "${hex(f64Bits(pos.secondsIntoBar), 16)}"`;
  out += ` :sections [${pos.sectionIds.join(' ')}]`;
  out += ` :prev-cue ${pos.prevCue === null ? 'none' : pos.prevCue}`;
  out += ` :next-cue ${pos.nextCue === null ? 'none' : pos.nextCue}`;
  if (pos.orderRow) {
    out += ` :order ${pos.orderRow.order} :row ${pos.orderRow.row}`;
    out += ` :tick-in-row ${pos.orderRow.tickInRow}`;
  }
  return `${out})\n`;
}

// ---------------------------------------------------------------------------
// The walk
// ---------------------------------------------------------------------------

const cases = readdirSync(corpusDir, { withFileTypes: true })
  .filter((e) => e.isDirectory() && !e.name.startsWith('.'))
  .map((e) => e.name)
  .sort();
assert.ok(cases.length > 0, 'no corpus cases found');

for (const name of cases) {
  test(`corpus parity: ${name}`, async () => {
    const dir = `${corpusDir}${name}/`;
    // A case with no golden is an unfinished case, not a parity failure;
    // say so, because the two read very differently in a gate's output.
    assert.ok(
      existsSync(`${dir}expected.sjon`),
      `${name} has no expected.sjon — run \`zig build corpus -- --update\``,
    );
    const golden = readFileSync(`${dir}expected.sjon`, 'utf8');
    assert.ok(golden.startsWith(GENERATED_HEADER), 'the golden names the verb that wrote it');
    const directives = parseHarness(readFileSync(`${dir}times.sjon`, 'utf8'));
    assert.ok(directives.length > 0, 'a case has to ask something');

    const chunks = chunksOf(golden);
    let next = 0;
    const take = () => chunks[next++];
    /** The head of the form a chunk is, e.g. `built` for `(built :kind …`. */
    const headOf = (chunk) => (chunk ?? '').match(/^\(([a-z][a-z0-9-]*)/)?.[1] ?? '';
    /**
     * Consume every chunk whose head is one of `heads` — how a directive
     * this walk cannot serve gets out of the way. By HEAD and not by
     * count, so a directive whose golden grows a child form (or loses
     * one) does not silently desynchronise the rest of the walk.
     */
    const skipForms = (...heads) => {
      while (next < chunks.length && heads.includes(headOf(chunks[next]))) next++;
    };

    // The fixture, pinned by name, length and hash before anything is
    // asked of it — the same line the runner writes first.
    const fixtureName = ['doc.sjon', 'song.mid', 'song.it'].find((f) => existsSync(dir + f));
    assert.ok(fixtureName, 'a case has a fixture');
    const fixture = readFileSync(dir + fixtureName);
    assert.equal(
      take(),
      `(fixture :file "${fixtureName}" :bytes ${fixture.length} :sha256 "${sha256(fixture)}")\n`,
      'the fixture line',
    );
    compared.fixture++;

    const needsDoc = directives.some((d) =>
      ['times', 'at', 'snap', 'dump', 'build'].includes(d.head),
    );
    if (!needsDoc) {
      skipped('the whole case asks about bytes, which no export hands out');
      return;
    }

    // Load the case's document exactly as the runner's env does: a
    // `doc.sjon` is one, and a `song.*` is dumped inside the wasm. A
    // sibling file is the anchor's referent — the runner reads it off
    // disk, and here it is attached.
    const t = await Tempura.instantiate(wasmModule);
    if (fixtureName === 'doc.sjon') {
      t.reload(fixture.toString('utf8'));
      for (const sibling of ['song.mid', 'song.it']) {
        if (existsSync(dir + sibling)) t.attachAnchor(readFileSync(dir + sibling));
      }
    } else {
      t.loadFile(fixture, fixtureName === 'song.mid' ? 'mid' : 'it');
    }

    const timeline = t.timeline();
    assert.ok(timeline, 'the document derived');
    assert.equal(renderEcho(timeline, t.diagnostics), take(), 'the (echo …) block');
    compared.echo++;

    // …and, for a case whose fixture is a FILE, the reconciliation's own
    // header: which of plan 04's five rules produced the timeline tier
    // and what each lane's hash verdict was. `tpr_loadFile` runs that
    // reconciliation — its diagnostics are in the `'TPDG'` blob — but the
    // VERDICT TABLE is `Dumped.verdicts`, and plan 10's frozen export set
    // has no `check-residue` row to hand it over.
    if (headOf(chunks[next]) === 'reconciled') {
      skipForms('reconciled');
      skipped('(reconciled …) — the verdict table, which no export hands out');
    }

    // …then one form per directive, in the order the harness spelled
    // them, exactly as the runner walks them.
    for (const d of directives) {
      if (d.head === 'times') {
        for (const bits of /** @type {string[]} */ (d.positional)) {
          const seconds = f64FromBits(BigInt(`0x${bits}`));
          const pos = t.at(seconds);
          assert.ok(pos, 'a position came back');
          assert.equal(
            renderPosition(pos, BigInt(`0x${bits}`)),
            take(),
            `(times "${bits}") on ${name}`,
          );
          compared.at++;
        }
      } else if (d.head === 'at') {
        const pos = t.atTick(BigInt(String(d.tick ?? 0)));
        assert.ok(pos, 'a position came back');
        assert.equal(renderPosition(pos, null), take(), `(at :tick ${d.tick}) on ${name}`);
        compared.at++;
      } else if (d.head === 'snap') {
        const swing = f64FromBits(BigInt(`0x${d.swing ?? '0000000000000000'}`));
        const tick = t.snap(BigInt(String(d.tick ?? 0)), /** @type {never} */ (d.grid), swing);
        assert.equal(`(snapped :tick ${tick})\n`, take(), `(snap …) on ${name}`);
        compared.snapped++;
      } else if (d.head === 'build') {
        const chunk = take() ?? '';
        if (d.cc !== undefined) {
          skipped('(build :cc N) — tpr_build carries no --cc');
          continue;
        }
        if (!chunk.includes('(residue ')) {
          skipped(
            "(build …) over an ANCHORED document — the runner writes the inline tier through the core's own writer, not through pipeline.build",
          );
          continue;
        }
        const bytes = t.build(/** @type {never} */ (d.kind === 'it' ? 'it' : 'mid'));
        assert.ok(bytes, `the build produced bytes: ${JSON.stringify(t.diagnostics)}`);
        const head = `(built :kind ${d.kind} :len ${bytes.length} :sha256 "${sha256(bytes)}"\n`;
        assert.equal(`${chunk.split('\n')[0]}\n`, head, `(build :kind ${d.kind}) on ${name}`);
        compared.built++;
      } else if (d.head === 'dump') {
        skipForms('dump');
        skipped('(dump) — the golden hashes a canonical re-print; tpr_text is the source');
      } else if (d.head === 'plan') {
        // `tpr_plan` hands back exactly `Plan.text()` and `tpr_apply` +
        // `tpr_text` hand back the applied document, so the ACTIONS and
        // the applied bytes are within reach — but `(planned …)`'s line
        // is the plan's SUMMARY (targets / set / inserted / removed /
        // replaced / inexact), which the frozen surface does not carry,
        // and a form compared in halves is not compared.
        skipForms('planned', 'applied');
        skipped("(plan …) — (planned …) is the plan's summary, which no export carries");
      } else if (d.head === 'export-score') {
        // Same shape: `tpr_exportScore(flags)` produces the text, and its
        // hash would match — but `(score …)` also pins `:meter`,
        // `:seconds-mode`, `:aggregated` and `:hints` off the exporter's
        // result, and takes `:max-keys` and the reconciliation's easing
        // hints as inputs, none of which the frozen surface spells.
        skipForms('score');
        skipped(
          '(export-score …) — (score …) pins exporter counts and takes hints no export spells',
        );
      } else {
        // `read`, `roundtrip`, `walk`, `write`: the golden's form is
        // named after the directive, so one rule covers all four.
        skipForms(d.head);
        skipped(`(${d.head}) — it asks about bytes, which no export hands out`);
      }
    }
    assert.equal(next, chunks.length, 'every form of the golden was accounted for');
  });
}

test('what the walk compared, and the closed set of what it could not', () => {
  // The gate on the gate, in two halves.
  //
  // First: the reasons a form went uncompared are a CLOSED set, written
  // down beside the surface that causes each. A reason outside it means a
  // new hole — a directive that used to be servable and stopped, or an
  // export that never grew the switch a golden needs — and it fails here,
  // loudly, instead of the walk quietly checking less than it did
  // yesterday. A SUBSET rather than an equality, because the corpus grows
  // a case at a time and a directive not yet exercised by any case is not
  // a regression; the counters below are what keep the walk honest in the
  // other direction.
  const closed = [
    '(build :cc N) — tpr_build carries no --cc',
    "(build …) over an ANCHORED document — the runner writes the inline tier through the core's own writer, not through pipeline.build",
    '(dump) — the golden hashes a canonical re-print; tpr_text is the source',
    '(export-score …) — (score …) pins exporter counts and takes hints no export spells',
    "(plan …) — (planned …) is the plan's summary, which no export carries",
    '(read) — it asks about bytes, which no export hands out',
    '(reconciled …) — the verdict table, which no export hands out',
    '(roundtrip) — it asks about bytes, which no export hands out',
    '(walk) — it asks about bytes, which no export hands out',
    '(write) — it asks about bytes, which no export hands out',
    'the whole case asks about bytes, which no export hands out',
  ];
  assert.deepEqual(
    [...nativeOnly].filter((reason) => !closed.includes(reason)),
    [],
    'a form went uncompared for a reason nobody wrote down',
  );

  // Second: every kind of form the wasm CAN produce was in fact produced
  // and compared. A refactor that turned the walk into a no-op — an
  // exception swallowed, a chunk index off by one, a `take()` that ran
  // out — leaves these at zero and is caught, which counting cases would
  // not do (the corpus grows; these five are the surface).
  assert.equal(compared.fixture, cases.length, 'every case pinned its fixture');
  assert.ok(compared.echo > 0, 'some (echo …) blocks were compared');
  assert.ok(compared.at > 0, 'some (at …) answers were compared');
  assert.ok(compared.snapped > 0, 'some (snapped …) answers were compared');
  assert.ok(compared.built > 0, 'some (built …) hashes were compared');
});
